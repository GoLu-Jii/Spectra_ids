# ============================================================
# 2. Save locally in Colab
# ============================================================

local_path = (
    "/content/"
    "dns_exfiltration_stateful_xgb_final.pkl"
)

joblib.dump(
    model_package,
    local_path
)


# ============================================================
# 3. Verify file
# ============================================================

print("\nFile saved:")
print(local_path)

print(
    "File exists:",
    os.path.exists(local_path)
)

