def load_stateful_file(
    relative_folder,
    filename,
    label
):

    file_path = os.path.join(
        BASE_DIR,
        relative_folder,
        filename
    )

    if not os.path.exists(file_path):

        raise FileNotFoundError(
            f"File not found:\n{file_path}"
        )

    df = pd.read_csv(file_path)

    # Target
    df["label"] = label

    # Original capture
    df["source"] = filename

    # Full path for traceability
    df["source_path"] = file_path

    return df


