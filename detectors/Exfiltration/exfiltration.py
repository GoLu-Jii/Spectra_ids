def parse_rr_type(value):
    """
    Convert rr_type into a Python set safely.
    Examples:
        "{'A'}"              -> {'A'}
        "{'AAAA', 'A'}"      -> {'AAAA', 'A'}
        "{'PTR'}"            -> {'PTR'}
        "set()"              -> set()
        None                 -> set()
    """

    if pd.isna(value):
        return set()

    if isinstance(value, set):
        return value

    try:
        parsed = ast.literal_eval(str(value))

        if isinstance(parsed, set):
            return parsed

        if isinstance(parsed, (list, tuple)):
            return set(parsed)

        return set()

    except Exception:
        return set()


