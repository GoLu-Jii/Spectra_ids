# 2. Canonicalize values
#
# We need deterministic representations for sets/dicts/lists.
# ============================================================

def canonicalize(value):

    # Missing / None
    if value is None:
        return "__NONE__"

    try:
        if pd.isna(value):
            return "__NONE__"
    except Exception:
        pass

    # Already a Python set
    if isinstance(value, set):
        items = [
            canonicalize(v)
            for v in value
        ]

        return (
            "SET",
            tuple(sorted(items, key=str))
        )

    # Dictionary
    if isinstance(value, dict):
        items = []

        for k, v in value.items():
            items.append(
                (
                    canonicalize(k),
                    canonicalize(v)
                )
            )

        return (
            "DICT",
            tuple(
                sorted(
                    items,
                    key=str
                )
            )
        )

    # List / tuple
    if isinstance(value, (list, tuple)):
        return (
            "LIST",
            tuple(
                canonicalize(v)
                for v in value
            )
        )

    # Strings that represent Python structures
    if isinstance(value, str):

        text = value.strip()

        # Try parsing only structure-like strings
        if (
            text.startswith(("{", "[", "("))
            or text in ["set()", "None"]
        ):

            try:
                parsed = ast.literal_eval(text)

                if parsed is None:
                    return "__NONE__"

                return canonicalize(parsed)

            except Exception:
                pass

        return text

    # Numeric values
    if isinstance(value, (int, float, np.integer, np.floating)):

        if isinstance(value, float) and np.isnan(value):
            return "__NONE__"

        return float(value)

    return str(value)


