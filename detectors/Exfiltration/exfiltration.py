loaded_package = joblib.load(
    local_path
)

loaded_model = loaded_package["model"]


# ============================================================
# 5. Verify metadata
# ============================================================

print(
    "Loaded model type:",
    loaded_package["model_type"]
)

print(
    "Task:",
    loaded_package["task"]
)

